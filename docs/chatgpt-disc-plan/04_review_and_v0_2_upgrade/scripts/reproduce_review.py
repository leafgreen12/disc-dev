#!/usr/bin/env python3
"""Reproduce the Vaga DISC review's local probes and arithmetic checks.

Requires Python 3.11+ and the installed jsonschema package. No network access,
package installation, source modification, approvals or application deployment.
Only use the exact, trusted source corpus from the reviewed ZIP. Source helpers
are imported as Python code after byte-level verification against this review's
inventory. These tests do not validate psychometrics or runtime authorization.
"""
from __future__ import annotations
import argparse
import hashlib
import importlib
import json
import random
import sys
from fractions import Fraction
from pathlib import Path
from typing import Any

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent


def read_json(path: Path) -> Any:
    def pairs(items: list[tuple[str, Any]]) -> dict[str, Any]:
        obj: dict[str, Any] = {}
        for key, value in items:
            if key in obj:
                raise ValueError(f"Duplicate JSON member in {path.name}")
            obj[key] = value
        return obj
    def reject_constant(value: str) -> Any:
        raise ValueError(f"Nonfinite JSON number: {value}")
    return json.loads(path.read_text(encoding="utf-8"),
                      object_pairs_hook=pairs, parse_constant=reject_constant)


def verify_source(source: Path) -> list[dict[str, Any]]:
    inventory = read_json(HERE / "source_inventory.json")
    results = []
    for entry in inventory:
        rel = Path(entry["path"])
        if rel.is_absolute() or ".." in rel.parts:
            raise ValueError("Invalid inventory path")
        path = source / rel
        if path.is_symlink() or not path.is_file():
            raise ValueError(f"Missing or symbolic source: {rel}")
        resolved = path.resolve()
        if not resolved.is_relative_to(source):
            raise ValueError("Source path escaped corpus")
        data = path.read_bytes()
        ok = len(data) == entry["bytes"] and hashlib.sha256(data).hexdigest() == entry["sha256"]
        results.append({"path": str(rel), "matched": ok})
    if not all(x["matched"] for x in results):
        bad = [x["path"] for x in results if not x["matched"]]
        raise ValueError("Corpus differs from reviewed bytes: " + ", ".join(bad[:8]))
    return results


def local_probes(source: Path) -> list[dict[str, Any]]:
    contracts_module = importlib.import_module("contract_doc13")
    policy_module = importlib.import_module("policy_doc14_reference")
    contracts = contracts_module.Contracts(source)
    policies = read_json(source / "DOC-14_AUTHORIZATION_REGISTRY.json")["operations"]
    policy = next(p for p in policies if p["api_id"] == "API-PAIR-001")
    results = []
    for original in read_json(HERE / "adversarial_probe_results.json"):
        if original["id"] == "PR06":
            actual = policy_module.evaluate(policy, original["input"])
        else:
            try:
                contracts.validate(original["schema"], original["input"])
                actual = "ACCEPT"
            except contracts_module.ContractError as exc:
                actual = "REJECT:" + str(exc)
        results.append({"id": original["id"], "input": original["input"],
                        "reviewer_expected": original["expected_by_reviewer"],
                        "actual": actual, "matches_previous_observation": actual == original["actual"]})
    return results


def arithmetic(source: Path) -> list[dict[str, Any]]:
    scorer = importlib.import_module("score_doc09_reference")
    bank = scorer.load_bank()
    rng = random.Random(20261015)
    rows = []
    for filename in ("DOC-09_PLAN_L40.json", "DOC-09_PLAN_L48.json"):
        plan = scorer.load_integer_json(source / filename)
        for n in range(30):
            values = {k["item_revision_ref"]: rng.randint(1, 5) for k in plan["items"]}
            if n >= 20:
                for ref in rng.sample(list(values), n - 19):
                    del values[ref]
            snapshot = {"schema_version": "0.1.0", "artifact_kind": "LOCAL_SYNTHETIC_SUBMISSION",
                        "submission_ref": f"probe-random-{n}", "submission_state": "SUBMITTED",
                        "responses": [{"item_revision_ref": k, "value": v} for k, v in values.items()]}
            for field in ("form_revision_ref", "context_ref", "instruction_ref", "scale_ref"):
                snapshot[field] = plan[field]
            expected = {}
            for dimension in ("D", "I", "S", "C"):
                keys = [k for k in plan["items"] if k["construct_code"] == dimension]
                present = [k for k in keys if k["item_revision_ref"] in values]
                # Independent signed-sum oracle, not generated by the scorer.
                keyed_sum = sum(values[k["item_revision_ref"]] * (1 if k["polarity"] == "FORWARD" else -1)
                                + (0 if k["polarity"] == "FORWARD" else 6) for k in present)
                value = Fraction(25 * (keyed_sum - len(keys)), len(keys)) if len(present) == len(keys) else None
                expected[dimension] = None if value is None else {"numerator": value.numerator, "denominator": value.denominator}
            computed = scorer.score(plan, snapshot, bank)
            actual = {d["code"]: d["linear_score"] for d in computed["dimensions"]}
            rows.append({"plan": plan["plan_id"], "case": n, "expected": expected,
                         "actual": actual, "passed": expected == actual})
    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True, help="Extracted vaga_disc_docs_dot_19 directory")
    parser.add_argument("--output", type=Path, required=True, help="A new JSON file outside source and this review pack")
    args = parser.parse_args()
    source = args.source.resolve()
    output = args.output.resolve()
    if not source.is_dir():
        parser.error("Source directory does not exist")
    if output.exists() or output.is_relative_to(source) or output.is_relative_to(HERE):
        parser.error("Output must be new and outside both source and review directories")
    if not output.parent.is_dir():
        parser.error("Output parent directory must exist")
    try:
        source_result = verify_source(source)
        sys.path.insert(0, str(source))
        probes = local_probes(source)
        sums = arithmetic(source)
        result = {"scope": "LOCAL_REVIEW_ONLY_NOT_RUNTIME_OR_SCIENTIFIC_VALIDATION",
                  "original_files_modified": False,
                  "source_files_checked": len(source_result),
                  "source_matches": all(x["matched"] for x in source_result),
                  "probes": probes, "arithmetic": sums,
                  "summary": {"observations_reproduced": sum(x["matches_previous_observation"] for x in probes),
                              "probe_count": len(probes), "arithmetic_passed": sum(x["passed"] for x in sums),
                              "arithmetic_total": len(sums)},
                  "production_authorized": False}
        # Verify again after running the inspected reference functions.
        verify_source(source)
        with output.open("x", encoding="utf-8") as handle:
            json.dump(result, handle, ensure_ascii=False, indent=2, allow_nan=False)
            handle.write("\n")
        print(json.dumps(result["summary"], ensure_ascii=False))
        return 0 if all(x["passed"] for x in sums) and all(x["matches_previous_observation"] for x in probes) else 1
    except (OSError, ValueError, ImportError, KeyError, StopIteration) as exc:
        print(f"Review reproduction failed: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
